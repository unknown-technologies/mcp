;; CONFIGURATION
XCSR		= #177564
XBUF		= #177566
RX2CS		= #177170
RX2DB		= #177172
WDCNT		= #200
MASK		= #100240	; BIT 15=ERR, 7=XFER-RQST, 5=DONE

		.ORG	0

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; TRAP VECTORS
_START:		NOP		; VECTOR 000: RESERVED (MUST BE NOP)
		BR	ENTRY
VECTO:		.WORD	TIMEOUT	; VECTOR 004: TIME OUT & OTHER ERRORS
		.WORD	300
VECILL:		.WORD	SIGILL	; VECTOR 010: ILLEGAL/RESERVED INSN
		.WORD	300
VECBPT:		.WORD	SIGBPT	; VECTOR 014: BPT INSN / T BIT
		.WORD	300
VECIOT:		.WORD	SIGIOT	; VECTOR 020: IOT INSTRUCTION
		.WORD	300
VECPWR:		.WORD	SIGPWR	; VECTOR 024: POWER FAIL
		.WORD	300
VECEMT:		.WORD	SIGEMT	; VECTOR 030: EMT INSTRUCTION
		.WORD	300
VECTRP:		.WORD	SIGTRAP	; VECTOR 034: TRAP INSTRUCTION
		.WORD	300
MEMSIZE:	.WORD	0	; 040
MONBASE:	.WORD	0	; 042
CURSECT:	.WORD	4	; 044
CURADDR:	.WORD	0	; 046
RXUNIT:		.WORD	0	; 050
CKSUM:		.WORD	0	; 052, PATCHED BY DISK BUILDER ROUTINE
MONSZ:		.WORD	0	; 054, PATCHED BY DISK BUILDER ROUTINE
MONCKSUM:	.WORD	0	; 056, PATCHED BY DISK BUILDER ROUTINE
VECCIN:		.WORD	CONIN	; VECTOR 060: CONSOLE INPUT DEVICE
		.WORD	0
VECCOT:		.WORD	CONOUT	; VECTOR 064: CONSOLE OUTPUT DEVICE
		.WORD	0
		.WORD	HLT	; VECTOR 070
		.WORD	0
		.WORD	HLT	; VECTOR 074
		.WORD	0
VECEVT:		.WORD	HLT	; VECTOR 100: EXTERNAL EVENT LINE INT
		.WORD	0
		.WORD	0	; VECTOR 104
		.WORD	0
		.WORD	0	; VECTOR 110
		.WORD	0
		.WORD	0	; VECTOR 114
		.WORD	0
		.WORD	0	; VECTOR 120
		.WORD	0
		.WORD	0	; VECTOR 124
		.WORD	0
		.WORD	0	; VECTOR 130
		.WORD	0
		.WORD	0	; VECTOR 134
		.WORD	0
		.WORD	0	; VECTOR 140
		.WORD	0
		.WORD	0	; VECTOR 144
		.WORD	0
		.WORD	0	; VECTOR 150
		.WORD	0
		.WORD	0	; VECTOR 154
		.WORD	0
		.WORD	0	; VECTOR 160
		.WORD	0
		.WORD	0	; VECTOR 164
		.WORD	0
		.WORD	0	; VECTOR 170
		.WORD	0
		.WORD	0	; VECTOR 174
		.WORD	0

TIMEOUT:
SIGILL:
SIGBPT:
SIGIOT:
SIGPWR:
SIGEMT:
SIGTRAP:
CONIN:
CONOUT:
HLT:		HALT

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; ACTUAL ENTRY POINT
ENTRY:		MOV	#200,	SP		; INITIALIZE STACK

		; VERIFY CHECKSUM OF BOOT BLOCK
		CLR	R0
		CLR	R1
		MOV	#377,	R2
CHECKSUM:	ADD	(R0)+,	R1
		SOB	R2,	CHECKSUM
		TST	R1
		BNE	CKSUMFAIL

		; SAVE RX02 UNIT
		MOV	@#RX2CS,RXUNIT
		BIC	#177757,RXUNIT

		; SIZE MEMORY
		MOV	#SZTRAP,VECTO
		CLR	R0
SIZELOOP:	TST	(R0)
		ADD	#4000,	R0
		BR	SIZELOOP

LOAD:		; R2 POINTS TO THE FIRST NON-EXISTANT ADDRESS
		MOV	R0,	MEMSIZE
		SUB	#4000,	R0		; COMPUTE MONITOR BASE
		MOV	R0,	MONBASE		; MONBASE = SIZE - 2048
		MOV	R0,	CURADDR

		; LOAD MONITOR IMAGE
LOADMON:	JSR	R5,	PUTC
		.WORD	56

		MOV	CURSECT,R0
		JSR	PC,	GETTRACKSECT

		MOV	CURADDR,R2
		JSR	PC,	READRX02

		INC	CURSECT
		ADD	#400,	CURADDR
		CMP	CURADDR,MEMSIZE
		BMI	LOADMON

		; VERIFY CHECKSUM OF MONITOR IMAGE
		MOV	MONBASE,R0
		CLR	R1
		MOV	MONSZ,	R2
		DEC	R2
CHECKSUM2:	ADD	(R0)+,	R1
		SOB	R2,	CHECKSUM2
		ADD	MONCKSUM,R1
		TST	R1
		BNE	CKSUMFAIL

		JSR	R5,	PUTS
		.WORD	NEWLINE

		JMP	@MONBASE

SZTRAP:		MOV	#LOAD,	(SP)
		MOV	#HLT,	VECTO
		RTI

CKSUMFAIL:	JSR	R5,	PUTS
		.WORD	CKSUMERR
		HALT

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
PUTS:		MOV	(R5)+,	R0
PRINT:		TSTB	(R0)
		BEQ	PREND
PRWAIT:		TSTB	@#XCSR
		BPL	PRWAIT
		MOVB	(R0)+,	@#XBUF
		BR	PRINT
PREND:		RTS	R5

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
PUTC:		TSTB	@#XCSR
		BPL	PUTC
		MOV	(R5)+,	@#XBUF
		RTS	R5

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; INPUT:  R0 = LOGICAL SECTOR
;; OUTPUT: R0 = TRACK, R1 = SECTOR
GETTRACKSECT:	MOV	#32,	R4
		MOV	R0,	R1
		CLR	R0
		DIV	R0,	R4		; R0 = LSN / 26
		MOV	R1,	R3		; R1 = LSN % 26
		ASL	R3			; R3 = R1 * 2
		CMP	R1,	#15		; IF(R1 >= 13) THEN
		BLT	GETTRACKSECT1
		INC	R3			;     R3++;
GETTRACKSECT1:	CLR	R2
		DIV	R2,	R4		; R3 %= 26
		MOV	R0,	R1
		ASL	R1
		MOV	R1,	R2		; R2 = TRACK * 2
		ASL	R1			; R1 = TRACK * 4
		ADD	R2,	R1		; R1 = TRACK * 6
		ADD	R1,	R3		; R3 += R1
		CLR	R2
		DIV	R2,	R4		; R3 %= 26
		MOV	R3,	R1
		INC	R1			; SECTOR = 1 + R5
		INC	R0			; TRACK++
		CMP	R0,	#115		; IF(TRACK >= 77) THEN
		BLT	GETTRACKSECT2
		CLR	R0			;     TRACK = 0
GETTRACKSECT2:	RTS	PC

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; READ SECTOR FROM RX02
;; R0 = TRACK, R1 = SECTOR, R2 = BUS ADDRESS
READRX02:	; LOAD CONSTANTS INTO REGISTERS TO SAVE SPACE
		MOV	#MASK,	R4
		MOV	#RX2CS,	R5

		; CHECK THAT RXV21 IS READY
		BIT	R4,	@R5		; APPLY MASK TO RX2CS
		BEQ	READRX02		; LOOP UNTIL ERR,
						; XFER-RQST OR DONE
		BMI	READRX02ERR		; HALT IF ERR IS SET

		; INITIATE A READ-SECTOR COMMAND
		MOV	#407,	R3		; DEN=DDEN, UNIT=0,
						; FN=RD-SECTOR, GO
		BIS	RXUNIT,	R3		; SET UNIT TO BOOT UNIT
		MOV	R3,	@R5		; DEN=DDEN, UNIT=BOOT,
						; FN=RD-SECTOR, GO
READRX02L0:	BIT	R4,	@R5		; APPLY MASK TO RX2CS
		BEQ	READRX02L0		; LOOP UNTIL ERR,
						; XFER-RQST OR DONE
		BMI	READRX02ERR		; HALT IF ERR IS SET

		; CODE ASSUMES THAT XFER-RQST IS NOW SET (IGNORES DONE)
		MOVB	R1,	@#RX2DB		; WRITE SECTOR NUMBER
READRX02L1:	BIT	R4,	@R5		; APPLY MASK
		BEQ	READRX02L1		; LOOP UNTIL ERR,
						; XFER-RQST OR DONE
		BMI	READRX02ERR		; HALT IF ERR IS SET

		; CODE ASSUMES THAT XFER-RQST IS NOW SET (IGNORES DONE)
		MOVB	R0,	@#RX2DB		; WRITE TRACK NUMBER

		; RXV21 IS NOW READING SECTOR DATA INTO ITS OWN BUFFER
READRX02L2:	BIT	R4,	@R5		; APPLY MASK
		BEQ	READRX02L2		; LOOP UNTIL ERR,
						; XFER-RQST OR DONE
		BMI	READRX02ERR		; HALT IF ERR IS SET

		; CODE ASSUMES THAT XFER-RQST IS NOW SET (IGNORES DONE)

		; THE SECTOR DATA IS NOW IN RXV21'S DATA BUFFER.
		; PREPARE TO TRANSFER SECTOR DATA FROM RXV21 TO RAM BY DMA
		MOV	#403,	@R5		; DEN=DDEN, UNIT=0,
						; FN=EMPTY-BUF, GO
READRX02L3:	BIT	R4,	@R5		; APPLY MASK
		BEQ	READRX02L3		; LOOP UNTIL ERR,
						; XFER-RQST OR DONE
		BMI	READRX02ERR		; HALT IF ERR IS SET

		; CODE ASSUMES THAT XFER-RQST IS NOW SET (IGNORES DONE)
		MOV	#WDCNT,	@#RX2DB		; LD WORD COUNT INTO RX2WC
READRX02L4:	BIT	R4,	@R5		; APPLY MASK
		BEQ	READRX02L4		; LOOP UNTIL ERR,
						; XFER-RQST OR DONE
		BMI	READRX02ERR		; HALT IF ERR IS SET

		; CODE ASSUMES THAT XFER-RQST IS NOW SET (IGNORES DONE)
		MOV	R2,	@#RX2DB		; LD BUS ADDR INTO RX2BA

		; DATA (256 BYTES) IS NOW BEING COPIED TO RAM VIA DMA
READRX02L5:	BIT	R4,	@R5		; APPLY MASK
		BEQ	READRX02L5		; LOOP UNTIL ERR,
						; XFER-RQST OR DONE
		BMI	READRX02ERR		; HALT IF ERR IS SET
		RTS	PC

READRX02ERR:	JSR	R5,	PUTS
		.WORD	RX02ERR
		HALT

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; DATA
RX02ERR:	"\r\nRX02 ERR"
CKSUMERR:	"\r\nCKSUM ERR"
NEWLINE:	"\r\n"
