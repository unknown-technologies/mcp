;; CONFIGURATION
XCSR		= #177564
XBUF		= #177566

		.ORG	0

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; TRAP VECTORS
_START:		NOP		; VECTOR 000: RESERVED (MUST BE NOP)
		BR	ENTRY
VECTO:		.WORD	TIMEOUT	; VECTOR 004: TIME OUT & OTHER ERRORS
		.WORD	300
VECILL:		.WORD	SIGILL	; VECTOR 010: ILLEGAL/RESERVED INSN
		.WORD	300
VECBPT:		.WORD	SIGBPT	; VECTOR 014: BPT INSN / T BIT
		.WORD	300
VECIOT:		.WORD	SIGIOT	; VECTOR 020: IOT INSTRUCTION
		.WORD	300
VECPWR:		.WORD	SIGPWR	; VECTOR 024: POWER FAIL
		.WORD	300
VECEMT:		.WORD	SIGEMT	; VECTOR 030: EMT INSTRUCTION
		.WORD	300
VECTRP:		.WORD	SIGTRAP	; VECTOR 034: TRAP INSTRUCTION
		.WORD	300
MEMSIZE:	.WORD	0	; 040
MONBASE:	.WORD	0	; 042
CURSECT:	.WORD	4	; 044
CURADDR:	.WORD	0	; 046
RXUNIT:		.WORD	0	; 050
CKSUM:		.WORD	0	; 052, PATCHED BY DISK BUILDER ROUTINE
MONSZ:		.WORD	0	; 054, PATCHED BY DISK BUILDER ROUTINE
MONCKSUM:	.WORD	0	; 056, PATCHED BY DISK BUILDER ROUTINE
VECCIN:		.WORD	CONIN	; VECTOR 060: CONSOLE INPUT DEVICE
		.WORD	0
VECCOT:		.WORD	CONOUT	; VECTOR 064: CONSOLE OUTPUT DEVICE
		.WORD	0
		.WORD	HLT	; VECTOR 070
		.WORD	0
		.WORD	HLT	; VECTOR 074
		.WORD	0
VECEVT:		.WORD	HLT	; VECTOR 100: EXTERNAL EVENT LINE INT
		.WORD	0
		.WORD	0	; VECTOR 104
		.WORD	0
		.WORD	0	; VECTOR 110
		.WORD	0
		.WORD	0	; VECTOR 114
		.WORD	0
		.WORD	0	; VECTOR 120
		.WORD	0
		.WORD	0	; VECTOR 124
		.WORD	0
		.WORD	0	; VECTOR 130
		.WORD	0
		.WORD	0	; VECTOR 134
		.WORD	0
		.WORD	0	; VECTOR 140
		.WORD	0
		.WORD	0	; VECTOR 144
		.WORD	0
		.WORD	0	; VECTOR 150
		.WORD	0
		.WORD	0	; VECTOR 154
		.WORD	0
		.WORD	0	; VECTOR 160
		.WORD	0
		.WORD	0	; VECTOR 164
		.WORD	0
		.WORD	0	; VECTOR 170
		.WORD	0
		.WORD	0	; VECTOR 174
		.WORD	0

TIMEOUT:
SIGILL:
SIGBPT:
SIGIOT:
SIGPWR:
SIGEMT:
SIGTRAP:
CONIN:
CONOUT:
HLT:		HALT

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; ACTUAL ENTRY POINT
ENTRY:		MOV	#200,	SP		; INITIALIZE STACK

		JSR	R5,	PUTS
		.WORD	MESSAGE

LOCKUP:		BR	LOCKUP

		HALT

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
PUTS:		MOV	(R5)+,	R0
PRINT:		TSTB	(R0)
		BEQ	PREND
PRWAIT:		TSTB	@#XCSR
		BPL	PRWAIT
		MOVB	(R0)+,	@#XBUF
		BR	PRINT
PREND:		RTS	R5

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; DATA
MESSAGE:	"MON000C NON-BOOTABLE VOLUME\r\n"
