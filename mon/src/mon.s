;; TTY INPUT / OUTPUT ROUTINES                                        ;;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTTTO: WRITE DATA INTO TT OUTPUT RING BUFFER
;; R0: BUFFER, R1: SIZE
EMTTTO:		TST	R1			; IF(SIZE == 0)
		BEQ	EMTTTORTI		;     RETURN

		TST	TTOSZ
		BNE	EMTTTOINIT

		MOVB	(R0)+,	@#XBUF
		DEC	R1
		BEQ	EMTTTORTI

EMTTTOINIT:	MOV	R1,	-(SP)
		MOV	R2,	-(SP)
		MOV	R3,	-(SP)


EMTTONEXT:	CMP	TTOSZ,	#400		; IF(TTOSZ < 256)
		BLT	EMTTTOWR
		
		MFPS	R3			; CLEAR PRIORITY BIT
		BIC	#300,	R3
		MTPS	R3

		EMT	6			; WAIT FOR IRQ (YIED)

		BIS	#300,	R3		; SET PRIORITY BIT
		MTPS	R3

		BR	EMTTONEXT

EMTTTOWR:	MOV	TTOWR,	R2
		MOV	R2,	R3
		ADD	TTOBUF,	R3
		MOVB	(R0)+,	(R3)
		INC	R2
		BIC	#177400,R2
		MOV	R2,	TTOWR
		INC	TTOSZ
		SOB	R1,	EMTTONEXT

		MOV	(SP)+,	R3
		MOV	(SP)+,	R2
		MOV	(SP)+,	R1

EMTTTORTI:	RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTTTI: READ DATA FROM TT INPUT RING BUFFER
;; R0: BUFFER, R1: SIZE
EMTTTI:		TST	TTISZ			; IF(TTISZ == 0)
		BEQ	EMTTTIZ			;     RETURN 0

		TST	R1			; IF(SIZE == 0)
		BEQ	EMTTTIZ			;     RETURN 0

		MOV	R1,	-(SP)
		MOV	R2,	-(SP)
		MOV	R3,	-(SP)
		MOV	R4,	-(SP)
		MOV	R5,	-(SP)

		CLR	R2			; CNT = 0
		MOV	TTIBUF,	R3		; R3 = TTIBUF
		MOV	TTIRD,	R4		; R4 = RD

EMTTTIL:	TST	TTISZ			; IF(TTISZ == 0)
		BEQ	EMTTTIE			;     RETURN CNT

		MOV	R3,	R5
		ADD	R4,	R5		; C = &TTIBUF[RD]
		MOVB	(R5),	(R0)+		; *(BUF++) = *C
		INC	R2			; CNT++
		INC	R4
		BIC	#177400,R4		; RD = (RD + 1) % BUFSZ
		DEC	TTISZ			; TTISZ--

		SOB	R1,	EMTTTIL

EMTTTIE:	MOV	R4,	TTIRD		; SAVE TTIRD POINTER

		MOV	R2,	R0		; RETURN CNT
		MOV	(SP)+,	R5
		MOV	(SP)+,	R4
		MOV	(SP)+,	R3
		MOV	(SP)+,	R2
		MOV	(SP)+,	R1
		RTI

EMTTTIZ:	CLR	R0			; RETURN 0
		RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; SIGTTIN: SERIAL CONSOLE INPUT INTERRUPT
SIGTTIN:	BIT	#200,	@#RCSR
		BEQ	SIGTTINRTI

		MOV	R0,	-(SP)
		MOV	R1,	-(SP)

		CMP	TTISZ,	#400
		BGE	SIGTTINE

		MOV	TTIBUF,	R0
		MOV	TTIWR,	R1
		ADD	R1,	R0
		MOVB	@#RBUF,	(R0)
		INC	R1
		BIC	#177400,R1
		MOV	R1,	TTIWR
		INC	TTISZ

SIGTTINE:	MOV	(SP)+,	R1
		MOV	(SP)+,	R0

SIGTTINRTI:	RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; SIGTTOU: SERIAL CONSOLE OUTPUT INTERRUPT
SIGTTOU:	TST	TTOSZ
		BEQ	SIGTTOE

		MOV	R0,	-(SP)
		MOV	R1,	-(SP)

		DEC	TTOSZ
		MOV	TTORD,	R0
		MOV	R0,	R1
		ADD	TTOBUF,	R1
		MOVB	(R1),	@#XBUF
		INC	R0
		BIC	#177400,R0
		MOV	R0,	TTORD

		MOV	(SP)+,	R1
		MOV	(SP)+,	R0

SIGTTOE:	RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTGETTIME: RETURN CURRENT TIME
EMTGETTIME:	MOV	HOUR,	R0
		MOV	MINUTE,	R1
		MOV	SECOND,	R2
		RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTSETTIME: SET CURRENT TIME
EMTSETTIME:	MOV	R0,	HOUR
		MOV	R1,	MINUTE
		MOV	R2,	SECOND
		CLR	TICKHZ
		RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTGETTICK: RETURN CURRENT TICK
EMTGETTICK:	MOV	TICK,	R0
		RTI


;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; TASK HANDLING AND CONTEXT SWITCHING ROUTINES                       ;;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; SIGEVT: LTC INTERRUPT
SIGEVT:		INC	TICK			; TICK++
		INC	TICKHZ			; TICKHZ++

		CMP	TICKHZ,	#62		; IF(TICKHZ < 50) THEN
		BLT	EMTYIELD		;     GOTO EMTYIELD

		CLR	TICKHZ			; TICKHZ = 0
		INC	SECOND			; SECOND++
		CMP	SECOND,	#74		; IF(SECOND < 60) THEN
		BLT	EMTYIELD		;     GOTO EMTYIELD

		CLR	SECOND			; SECOND = 0
		INC	MINUTE			; MINUTE++
		CMP	MINUTE,	#74		; IF(MINUTE < 60) THEN
		BLT	EMTYIELD		;     GOTO EMTYIELD

		CLR	MINUTE			; MINUTE = 0
		INC	HOUR			; HOUR++
		CMP	HOUR,	#30		; IF(HOUR < 24) THEN
		BLT	EMTYIELD		;     GOTO EMTYIELD

		CLR	HOUR			; HOUR = 0

		; END OF DAY PROCESSING
		TST	NEXTDAY			; IF(!NEXTDAY) THEN
		BEQ	EMTYIELD		;    GOTO EMTYIELD
		JSR	PC,	@NEXTDAY	; NEXTDAY()

EMTYIELD:	; GET NEXT TASK: SCHEDULING FUNCTION AVAILABLE?
		TST	SCHEDULE
		BEQ	SIGEVTE

		; SAVE CONTEXT
		MOV	R0,	-(SP)
		MOV	R1,	-(SP)
		MOV	R2,	-(SP)
		MOV	R3,	-(SP)
		MOV	R4,	-(SP)
		MOV	R5,	-(SP)

		; C CALL TO SCHEDULE(SP)
		MOV	SP,	-(SP)
		JSR	PC,	@SCHEDULE
		TST	(SP)+
		MOV	R0,	SP

		; RESTORE CONTEXT
		MOV	(SP)+,	R5
		MOV	(SP)+,	R4
		MOV	(SP)+,	R3
		MOV	(SP)+,	R2
		MOV	(SP)+,	R1
		MOV	(SP)+,	R0
SIGEVTE:	RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTSPAWN: CREATE NEW TASK
;; R0: STACK, R1: TARGET PROGRAM COUNTER
EMTSPAWN:	CLR	-(R0)			; PSW
		MOV	R1,	-(R0)		; PC
		CLR	-(R0)			; R0
		CLR	-(R0)			; R1
		CLR	-(R0)			; R2
		CLR	-(R0)			; R3
		CLR	-(R0)			; R4
		CLR	-(R0)			; R5

		RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTMTXLK: LOCK MUTEX
;; R0: LOCK WORD ADDRESS
EMTMTXLK:	TST	(R0)
		BEQ	EMTMTXLKE
		EMT	6			; YIELD
		BR	EMTMTXLK
EMTMTXLKE:	INC	(R0)
		RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTMTXULK: UNLOCK MUTEX
;; R0: LOCK WORD ADDRESS
EMTMTXUL:	TST	(R0)
		BEQ	EMTMTXULE
		CLR	(R0)
EMTMTXULE:	RTI

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;; EMTHALTSYS: FLUSH TTO BUFFER AND HALT
EMTHALTSYS:	CLR	SCHEDULE		; DISABLE SCHEDULING

		MFPS	R0			; ALLOW IRQS
		BIC	#200,	R0
		MTPS	R0

EMTHALTL:	TST	TTOSZ			; WAIT UNTIL TTO BUF
		BNE	EMTHALTL		; IS EMPTY

EMTHALTE:	JSR	R5,	PUTS		; PRINT FINAL MESSAGE
		.WORD	HALTMSG
		JSR	R5,	PUTS
		.WORD	NEWLINE

		HALT				; HALT CPU
EMTHALTLOCK:	BR	EMTHALTLOCK


